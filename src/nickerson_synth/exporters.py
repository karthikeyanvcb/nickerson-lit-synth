"""CSV / JSON / LaTeX exports of a taxonomy and an audit run."""

from __future__ import annotations

import csv
import re
from collections.abc import Mapping
from pathlib import Path

from nickerson_synth.models import AuditRun, Taxonomy

# --------------------------------------------------------------------------- #
# CSV
# --------------------------------------------------------------------------- #


def write_matrix_csv(run: AuditRun, path: str | Path) -> None:
    """Wide matrix: one row per paper, two columns per dimension (codes, status)."""
    dims = run.taxonomy.dimensions
    header = ["paper_id"]
    for d in dims:
        header += [d.id, f"{d.id}__status"]
    header += ["error"]
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(header)
        for p in run.papers:
            row = [p.paper_id]
            for d in dims:
                c = p.get(d.id)
                if p.error or c is None:
                    row += ["", "error" if p.error else "missing"]
                else:
                    row += [";".join(c.characteristic_ids), c.status]
            row.append(p.error or "")
            w.writerow(row)


def write_evidence_csv(run: AuditRun, path: str | Path) -> None:
    """Long format: one row per evidence quote (or per classification without quotes)."""
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(
            [
                "paper_id",
                "dimension_id",
                "characteristic_ids",
                "status",
                "confidence",
                "claimed_page",
                "matched_page",
                "quote_verified",
                "quote",
                "rationale",
                "proposed_characteristic",
                "issues",
            ]
        )
        for p in run.papers:
            for c in p.classifications:
                base = [
                    p.paper_id,
                    c.dimension_id,
                    ";".join(c.characteristic_ids),
                    c.status,
                    f"{c.confidence:.2f}",
                ]
                tail = [c.rationale, c.proposed_characteristic or "", " | ".join(c.issues)]
                if not c.evidence:
                    w.writerow([*base, "", "", "", "", *tail])
                for e in c.evidence:
                    w.writerow([*base, e.page, e.matched_page or "", e.verified, e.quote, *tail])


def write_coverage_csv(run: AuditRun, path: str | Path) -> None:
    """How many papers each characteristic classifies (Nickerson objective condition)."""
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["dimension_id", "characteristic_id", "n_papers"])
        for key, n in run.characteristic_counts().items():
            dim, char = key.split(".", 1)
            w.writerow([dim, char, n])


def write_all(run: AuditRun, out_dir: str | Path) -> dict[str, Path]:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    paths = {
        "json": out / "audit.json",
        "matrix": out / "matrix.csv",
        "evidence": out / "evidence.csv",
        "coverage": out / "coverage.csv",
    }
    run.save(paths["json"])
    write_matrix_csv(run, paths["matrix"])
    write_evidence_csv(run, paths["evidence"])
    write_coverage_csv(run, paths["coverage"])
    return paths


def read_bibkeys(path: str | Path) -> dict[str, str]:
    """Read a two-column CSV ``paper_id,bibkey`` (header optional)."""
    keys: dict[str, str] = {}
    with open(path, newline="", encoding="utf-8") as f:
        for row in csv.reader(f):
            if len(row) >= 2 and row[0].strip() and row[0].strip().lower() != "paper_id":
                keys[row[0].strip()] = row[1].strip()
    return keys


