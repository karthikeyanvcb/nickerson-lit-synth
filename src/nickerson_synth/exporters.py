_LATEX_SPECIAL = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}
_LATEX_RE = re.compile("|".join(re.escape(k) for k in _LATEX_SPECIAL))


def latex_escape(text: str) -> str:
    return _LATEX_RE.sub(lambda m: _LATEX_SPECIAL[m.group()], text)


_PREAMBLE_NOTE = (
    "% Generated by nickerson-lit-synth. Requires in the preamble:\n"
    "%   \\usepackage{booktabs,tabularx,graphicx,amssymb}\n"
)


def taxonomy_table(
    taxonomy: Taxonomy,
    caption: str | None = None,
    label: str = "tab:taxonomy",
    star: bool = True,
) -> str:
    """Dimension | ME/NE | characteristics table."""
    env = "table*" if star else "table"
    cap = latex_escape(caption or f"{taxonomy.name}: dimensions and characteristics")
    lines = [
        _PREAMBLE_NOTE.rstrip("\n"),
        f"\\begin{{{env}}}[t]",
        "\\centering",
        "\\small",
        f"\\caption{{{cap}}}",
        f"\\label{{{label}}}",
        "\\begin{tabularx}{\\textwidth}{@{}l c X@{}}",
        "\\toprule",
        "\\textbf{Dimension} & \\textbf{ME/NE} & \\textbf{Characteristics} \\\\",
        "\\midrule",
    ]
    for d in taxonomy.dimensions:
        chars = "; ".join(latex_escape(c.label) for c in d.characteristics)
        lines.append(f"{latex_escape(d.label)} & {'ME' if d.exclusive else 'NE'} & {chars} \\\\")
    lines += [
        "\\bottomrule",
        "\\end{tabularx}",
        "\\par\\smallskip{\\footnotesize "
        f"Meta-characteristic: {latex_escape(taxonomy.meta_characteristic.rstrip('.'))}. "
        "ME = mutually exclusive (one characteristic per object); "
        "NE = non-exclusive.\\par}",
        f"\\end{{{env}}}",
    ]
    return "\n".join(lines) + "\n"


def matrix_table(
    run: AuditRun,
    bibkeys: Mapping[str, str] | None = None,
    caption: str | None = None,
    label: str = "tab:classification",
    verified_only: bool = False,
    star: bool = True,
) -> str:
    """Paper x characteristic matrix with check marks, grouped by dimension.

    Verified codes get ``$\\checkmark$``; codes whose evidence could not be
    verified get ``($\\checkmark$)`` unless ``verified_only`` drops them.
    """
    tax = run.taxonomy
    bibkeys = bibkeys or {}
    env = "table*" if star else "table"
    cap = latex_escape(caption or f"Classification of the surveyed literature ({tax.name})")
    colspec = "@{}X" + "".join(" | " + "c" * len(d.characteristics) for d in tax.dimensions) + "@{}"

    group = " & ".join(
        f"\\multicolumn{{{len(d.characteristics)}}}{{c}}{{\\textbf{{{latex_escape(d.label)}}}}}"
        for d in tax.dimensions
    )
    rules = []
    col = 2
    for d in tax.dimensions:
        rules.append(f"\\cmidrule(lr){{{col}-{col + len(d.characteristics) - 1}}}")
        col += len(d.characteristics)
    heads = " & ".join(
        f"\\rotatebox{{90}}{{{latex_escape(c.label)}}}"
        for d in tax.dimensions
        for c in d.characteristics
    )

    lines = [
        _PREAMBLE_NOTE.rstrip("\n"),
        f"\\begin{{{env}}}[t]",
        "\\centering",
        "\\scriptsize",
        f"\\caption{{{cap}}}",
        f"\\label{{{label}}}",
        f"\\begin{{tabularx}}{{\\textwidth}}{{{colspec}}}",
        "\\toprule",
        f"\\textbf{{Study}} & {group} \\\\",
        " ".join(rules),
        f" & {heads} \\\\",
        "\\midrule",
    ]
    for p in run.papers:
        if p.error:
            continue
        key = bibkeys.get(p.paper_id)
        study = f"\\cite{{{key}}}" if key else latex_escape(p.paper_id)
        cells: list[str] = []
        for d in tax.dimensions:
            c = p.get(d.id)
            for ch in d.characteristics:
                mark = ""
                if c and not c.unclassifiable and ch.id in c.characteristic_ids:
                    if c.verified:
                        mark = "$\\checkmark$"
                    elif not verified_only:
                        mark = "($\\checkmark$)"
                cells.append(mark)
        lines.append(f"{study} & {' & '.join(cells)} \\\\")
    note = (
        "$\\checkmark$ = coded with verbatim evidence verified against the PDF"
        + ("" if verified_only else "; ($\\checkmark$) = coded, evidence not verified")
        + "."
    )
    lines += [
        "\\bottomrule",
        "\\end{tabularx}",
        f"\\par\\smallskip{{\\footnotesize {note}\\par}}",
        f"\\end{{{env}}}",
    ]
    return "\n".join(lines) + "\n"
